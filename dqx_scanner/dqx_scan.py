"""
DQX Puzzle Scanner - the fixed and rebuilt DEUS-QUANTUM-X.

Searches the "~1000 BTC" Bitcoin puzzle ranges (built in: #66-#100, with
#71-#100 as the targets) or any range/address you set yourself.

What changed compared with DEUS-QUANTUM-X
-----------------------------------------
* The modules that never searched anything (GA on address similarity, RL,
  "Grover"/"Shor"/D-Wave stubs, lattice stubs, "self-writing" file copies,
  random "AI predictions") are gone. Hash outputs carry no gradient, so none
  of them can beat an exhaustive scan; they only burned time and crashed.
* Keys are generated by batched elliptic-curve point addition: one modular
  inverse shared by 4096 keys, and each inverse serves both C+iG and C-iG.
  That is about 10-13x faster per core than one scalar multiplication per
  key (the old code), measured at ~275k keys/s/core vs ~21k.
* Compares 20-byte hash160 values, never Base58 strings, and checks every
  target at once (a set lookup).
* Real multi-core (one process per core) with clean Ctrl+C handling.
* Checkpoints are tied to the exact range + chunk size, so changing the range
  can never silently resume a stale position (the old bug).
* A found key is verified independently, written to FOUND_KEYS.txt with WIF,
  fsync'ed, and every worker stops.
* Standard library only. Runs on Linux, macOS and Windows, Python 3.8+.
  RIPEMD-160 falls back to pycryptodome or a built-in pure-Python version if
  your OpenSSL build lacks it.

Commands
--------
  python dqx_scan.py list                     # puzzles, ranges, prizes, odds
  python dqx_scan.py list --online            # + live balance via mempool.space
  python dqx_scan.py selftest                 # proves the scanner on solved puzzles
  python dqx_scan.py bench                    # your keys/s and expected times

  python dqx_scan.py scan --puzzle 71         # one puzzle (random chunks)
  python dqx_scan.py scan --puzzle 71-100     # all unsolved puzzles #71-#100
  python dqx_scan.py scan --puzzle 71 --mode sequential
  python dqx_scan.py scan --puzzle 71 --start 50% --end 60%         # set range
  python dqx_scan.py scan --puzzle 71 --start 0x5a0000000000000000 --end 0x5affffffffffffffff
  python dqx_scan.py scan --puzzle 71 --shard 3/8                    # machine 3 of 8
  python dqx_scan.py scan --address 1BY8GQbnueYofwSuFAT3USAhGjPrkxDdW9 \
                          --start 730fc235c1942c1a0 --end 730fc235c1942c2ae

Positions (--start/--end) are hex (with or without 0x), "dec:<decimal>", or a
percentage of the puzzle range such as "37.5%". Both ends are inclusive.
Progress is saved in dqx_state.db; run the same command again to resume.
Create a file named STOP in the working directory to stop gracefully.

Be realistic: puzzle #71 has 2^70 keys. A CPU in Python checks ~10^6 keys/s;
the public pools scan ~10^11 keys/s. Run `bench` to see the numbers for your
machine before spending electricity.
"""

