def parse_puzzles(spec: str) -> List[int]:
    out: List[int] = []
    for part in spec.split(","):
        part = part.strip()
        if "-" in part:
            lo, hi = (int(x) for x in part.split("-", 1))
            out.extend(range(lo, hi + 1))
        elif part:
            out.append(int(part))
    bad = [n for n in out if n not in PUZZLES]
    if bad:
        raise SystemExit(f"Unknown puzzle(s) {bad}. Built in: #{min(PUZZLES)}-#{max(PUZZLES)}.")
    return sorted(set(out))


def parse_pos(text: str, lo: int, hi: int) -> int:
    """hex (0x optional), 'dec:<n>', or 'x%' of [lo, hi]."""
    s = text.strip().lower().replace("_", "")
    if s.endswith("%"):
        frac = Fraction(s[:-1]) / 100
        if not 0 <= frac <= 1:
            raise SystemExit(f"Percentage out of range: {text}")
        return lo + int((hi - lo) * frac)
    if s.startswith("dec:"):
        return int(s[4:], 10)
    return int(s[2:] if s.startswith("0x") else s, 16)


def apply_shard(lo: int, hi: int, shard: str) -> Tuple[int, int]:
    i, n = (int(x) for x in shard.split("/"))
    if not 1 <= i <= n:
        raise SystemExit("--shard must look like 3/8 (part 3 of 8, 1-based)")
    size = hi - lo + 1
    a = lo + size * (i - 1) // n
    b = lo + size * i // n - 1
    return a, b


def build_jobs(args) -> List[Job]:
    chunk = 1 << args.chunk_bits
    jobs: List[Job] = []
    if args.address:
        if args.puzzle:
            raise SystemExit("Use either --puzzle or --address, not both.")
        if not (args.start and args.end):
            raise SystemExit("--address needs --start and --end (hex).")
        for a in args.address:
            try:
                address_to_hash160(a)  # validate early
            except ValueError as e:
                raise SystemExit(f"Bad --address: {e}")
        lo = parse_pos(args.start, 1, N - 1)
        hi = parse_pos(args.end, 1, N - 1)
        if args.shard:
            lo, hi = apply_shard(lo, hi, args.shard)
        jobs.append(Job("custom", list(args.address), lo, hi, chunk))
    else:
        if not args.puzzle:
            raise SystemExit("Give --puzzle (e.g. 71 or 71-100) or --address with --start/--end.")
        nums = parse_puzzles(args.puzzle)
        if not args.include_solved:
            skipped = [n for n in nums if n in KNOWN_SOLVED]
            nums = [n for n in nums if n not in KNOWN_SOLVED]
            if skipped:
                log.info("Skipping known-solved puzzle(s) %s (use --include-solved to scan them anyway).",
                         ", ".join(f"#{n}" for n in skipped))
        if not nums:
            raise SystemExit("No puzzles left to scan.")
        if len(nums) > 1 and not all(x.strip().endswith("%") for x in (args.start, args.end) if x):
            raise SystemExit("With several puzzles, --start/--end must be percentages (e.g. 25%).")
        for n in nums:
            lo, hi = puzzle_range(n)
            a = parse_pos(args.start, lo, hi) if args.start else lo
            b = parse_pos(args.end, lo, hi) if args.end else hi
            if not (lo <= a <= b <= hi):
                raise SystemExit(f"#{n}: range {hex(a)}..{hex(b)} is outside the puzzle range {hex(lo)}..{hex(hi)}")
            if args.shard:
                a, b = apply_shard(a, b, args.shard)
            jobs.append(Job(f"#{n}", [PUZZLES[n]], a, b, chunk, puzzle=n))
    for j in jobs:
        if not (1 <= j.start <= j.end < N):
            raise SystemExit(f"{j.label}: invalid range {hex(j.start)}..{hex(j.end)}")
    return jobs


def cmd_scan(args) -> int:
    jobs = build_jobs(args)
    mode = args.mode
    if mode == "auto":
        mode = "random" if max(j.size for j in jobs) > (1 << 48) else "sequential"
    if len([j for j in jobs if j.puzzle]) > 1:
        smallest = min(j.puzzle for j in jobs if j.puzzle)
        log.info("Note: a key checked in #%d is 2^%d times more likely to win than one in #%d. "
                 "Chunks are split evenly across the selected puzzles.",
                 smallest, max(j.puzzle for j in jobs if j.puzzle) - smallest, max(j.puzzle for j in jobs if j.puzzle))
    run_scan(jobs, mode, args.workers, args.state, args.found,
             status_every=args.status_every, stop_file=args.stop_file)
    return 0


def fetch_balance(addr: str, timeout: float = 15.0) -> Optional[Tuple[int, int]]:
    """(balance_sat, tx_count) from mempool.space, or None on error."""
    try:
        req = urllib.request.Request(f"https://mempool.space/api/address/{addr}",
                                     headers={"User-Agent": f"dqx-scan/{__version__}"})
        with urllib.request.urlopen(req, timeout=timeout) as r:
            d = json.loads(r.read().decode())
        cs, ms = d["chain_stats"], d["mempool_stats"]
        bal = cs["funded_txo_sum"] - cs["spent_txo_sum"] + ms["funded_txo_sum"] - ms["spent_txo_sum"]
        return bal, cs["tx_count"] + ms["tx_count"]
    except Exception as e:  # network errors are expected offline
        log.debug("balance lookup failed for %s: %s", addr, e)
        return None


