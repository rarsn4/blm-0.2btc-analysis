def _pick_ripemd160():
    """Return (name, fast_proto_or_None, func). fast_proto supports .copy()."""
    try:
        proto = hashlib.new("ripemd160")
        proto.copy().update(b"")
        return "hashlib/OpenSSL", proto, lambda d: hashlib.new("ripemd160", d).digest()
    except (ValueError, TypeError):
        pass
    try:
        from Crypto.Hash import RIPEMD160  # pycryptodome
        return "pycryptodome", None, lambda d: RIPEMD160.new(d).digest()
    except ImportError:
        pass
    return "pure-python (slow: pip install pycryptodome)", None, _ripemd160_pure


RIPEMD_BACKEND, _RMD_PROTO, ripemd160 = _pick_ripemd160()


def hash160(data: bytes) -> bytes:
    return ripemd160(_sha256(data).digest())


