###############################################################################
# The scanner core (runs inside worker processes)
###############################################################################
HALF = 2048                 # keys on each side of a group centre
GROUP = 2 * HALF + 1        # keys per group (4097)

_TX: List[int] = []         # x of (i+1)*G, i < HALF
_TY: List[int] = []
_J: Point = None            # GROUP * G, moves the centre to the next group
_TARGETS: Set[bytes] = set()
_STOP = None                # multiprocessing.Event shared by all workers


def _build_tables() -> None:
    global _J
    if _TX:
        return
    q = G
    for _ in range(HALF):
        _TX.append(q[0])
        _TY.append(q[1])
        q = ec_add(q, G)
    _J = ec_mul(GROUP)


class _NoStop:
    @staticmethod
    def is_set() -> bool:
        return False


def scan_range(a: int, b: int, targets: Set[bytes], stop=None) -> Tuple[int, List[int], bool]:
    """
    Check every private key in [a, b] (inclusive, 1 <= a <= b < N).
    Returns (keys_checked, matching_keys, finished).

    Keys are visited in groups centred on c: c, c+1..c+m and c-1..c-m.
    For each i, (c +/- i)G = C +/- iG share the denominator x(iG) - x(C), so a
    single Montgomery batch inversion per group gives every slope.
    """
    if not (1 <= a <= b < N):
        raise ValueError("range must satisfy 1 <= start <= end < curve order")
    _build_tables()
    stop = stop or _NoStop
    sha = _sha256
    proto = _RMD_PROTO
    rmd = ripemd160
    pref = (b"\x02", b"\x03")
    hits: List[int] = []
    checked = 0
    k = a
    cx = cy = None
    while k <= b:
        if stop.is_set():
            return checked, hits, False
        rem = b - k + 1
        m = HALF if rem >= GROUP else (rem - 1) // 2
        c = k + m
        if cx is None or m != HALF:
            cx, cy = ec_mul(c)
        TX = _TX if m == HALF else _TX[:m]
        TY = _TY if m == HALF else _TY[:m]

        # centre
        pub = pref[cy & 1] + cx.to_bytes(32, "big")
        if proto is not None:
            r = proto.copy(); r.update(sha(pub).digest()); h = r.digest()
        else:
            h = rmd(sha(pub).digest())
        if h in targets:
            hits.append(c)

        if m:
            # Montgomery batch inversion of (x(iG) - x(C)) for i = 1..m
            acc = []
            t = 1
            for tx in TX:
                t = t * (tx - cx) % P
                acc.append(t)
            inv = pow(t, -1, P)
            invs = [0] * m
            for i in range(m - 1, 0, -1):
                invs[i] = inv * acc[i - 1] % P
                inv = inv * (TX[i] - cx) % P
            invs[0] = inv

            i = 1
            if proto is not None:
                for tx, ty, iv in zip(TX, TY, invs):
                    lam = (ty - cy) * iv % P                    # C + iG
                    x3 = (lam * lam - cx - tx) % P
                    y3 = (lam * (cx - x3) - cy) % P
                    r = proto.copy(); r.update(sha(pref[y3 & 1] + x3.to_bytes(32, "big")).digest())
                    if r.digest() in targets:
                        hits.append(c + i)
                    lam = -(ty + cy) * iv % P                   # C - iG
                    x3 = (lam * lam - cx - tx) % P
                    y3 = (lam * (cx - x3) - cy) % P
                    r = proto.copy(); r.update(sha(pref[y3 & 1] + x3.to_bytes(32, "big")).digest())
                    if r.digest() in targets:
                        hits.append(c - i)
                    i += 1
            else:
                for tx, ty, iv in zip(TX, TY, invs):
                    lam = (ty - cy) * iv % P
                    x3 = (lam * lam - cx - tx) % P
                    y3 = (lam * (cx - x3) - cy) % P
                    if rmd(sha(pref[y3 & 1] + x3.to_bytes(32, "big")).digest()) in targets:
                        hits.append(c + i)
                    lam = -(ty + cy) * iv % P
                    x3 = (lam * lam - cx - tx) % P
                    y3 = (lam * (cx - x3) - cy) % P
                    if rmd(sha(pref[y3 & 1] + x3.to_bytes(32, "big")).digest()) in targets:
                        hits.append(c - i)
                    i += 1

        n = 2 * m + 1
        if m < HALF and rem == n + 1:      # even remainder: one key left (c+m+1)
            ex, ey = ec_add((cx, cy), (_TX[m], _TY[m]))
            if hash160(pref[ey & 1] + ex.to_bytes(32, "big")) in targets:
                hits.append(c + m + 1)
            n += 1
        checked += n
        k += n
        if m == HALF and b - k + 1 >= GROUP:
            cx, cy = ec_add((cx, cy), _J)  # next centre = c + GROUP
        else:
            cx = None
    return checked, hits, True


def _worker_init(targets: Set[bytes], stop_event) -> None:
    global _TARGETS, _STOP
    try:
        signal.signal(signal.SIGINT, signal.SIG_IGN)  # the main process handles Ctrl+C
    except (ValueError, OSError):
        pass
    if hasattr(os, "nice"):
        try:
            os.nice(5)  # stay polite to the rest of the machine
        except OSError:
            pass
    _TARGETS = targets
    _STOP = stop_event
    _build_tables()


def _worker_task(task: Tuple[int, int, int, int]) -> dict:
    job, idx, a, b = task
    t0 = time.perf_counter()
    keys, hits, finished = scan_range(a, b, _TARGETS, _STOP)
    return {"job": job, "idx": idx, "keys": keys, "hits": hits,
            "finished": finished, "secs": time.perf_counter() - t0}


