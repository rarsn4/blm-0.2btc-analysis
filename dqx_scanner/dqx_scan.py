FOUND_BANNER = """
###############################################################################
#  KEY FOUND - {label}
#  address : {address}
#  key hex : {key_hex}
#  WIF     : {wif}
#  saved to: {path}
#
#  DO NOT broadcast a spend through the public mempool. A spend reveals the
#  public key, and a key this small is recovered with Pollard's kangaroo in
#  seconds: bots will replace your transaction with a higher-fee one. Submit
#  it privately to a mining pool (non-public transaction submission).
###############################################################################
"""


def save_found(path: str, label: str, address: str, key: int) -> None:
    line = (f"{time.strftime('%Y-%m-%d %H:%M:%S')} | {label} | {address} | "
            f"hex={key:064x} | WIF={key_to_wif(key)}\n")
    with open(path, "a", encoding="utf-8") as f:
        f.write(line)
        f.flush()
        os.fsync(f.fileno())


def run_scan(jobs: List[Job], mode: str, workers: int, state_path: str, found_path: str,
             status_every: float = 15.0, stop_file: Optional[str] = "STOP",
             stop_on_found: bool = True, announce: bool = True) -> List[Tuple[str, str, int]]:
    """Run the scan; returns a list of (label, address, key) found."""
    targets: Dict[bytes, Tuple[str, str]] = {}
    for j in jobs:
        for addr in j.addresses:
            targets[address_to_hash160(addr)] = (j.label, addr)
    target_set = set(targets)

    db = StateDB(state_path)
    planner = Planner(jobs, mode, db)
    for j in jobs[:4]:
        log.info("%s: range %s..%s (%s keys, %s chunks of %s), already scanned %s",
                 j.label, hex(j.start), hex(j.end), fmt_num(j.size), fmt_num(j.nchunks),
                 fmt_num(j.chunk_size), fmt_pct(100 * j.keys_done / j.size))
    if len(jobs) > 4:
        log.info("... and %d more ranges: %s", len(jobs) - 4, " ".join(j.label for j in jobs[4:]))
    if not planner.active():
        log.info("Nothing left to scan for these ranges (all chunks done). Use another range or --state file.")
        db.close()
        return []

    ctx = mp.get_context("spawn")
    stop_event = ctx.Event()
    found: List[Tuple[str, str, int]] = []
    session_keys = 0
    t_start = time.time()
    t_status = t_start
    stopping = False
    max_inflight = workers * 2

    def handle_hits(res: dict) -> None:
        for k in res["hits"]:
            h = hash160(pubkey_compressed(k))  # independent re-check, not the batched path
            if h not in targets:
                log.error("Worker reported key %s but it does not verify - please report this.", hex(k))
                continue
            label, addr = targets[h]
            save_found(found_path, label, addr, k)
            db.record_found(label, addr, k)
            found.append((label, addr, k))
            if announce:
                print(FOUND_BANNER.format(label=label, address=addr, key_hex=f"{k:064x}",
                                          wif=key_to_wif(k), path=os.path.abspath(found_path)), flush=True)
            else:
                log.info("found %s key %s", label, hex(k))

    log.info("Starting %d worker(s), mode=%s, RIPEMD-160 backend: %s", workers, mode, RIPEMD_BACKEND)
    pool = cf.ProcessPoolExecutor(max_workers=workers, mp_context=ctx,
                                  initializer=_worker_init, initargs=(target_set, stop_event))
    inflight: Dict[cf.Future, Tuple[int, int, int, int]] = {}
    try:
        while True:
            while not stopping and len(inflight) < max_inflight:
                task = planner.next_task()
                if task is None:
                    break
                inflight[pool.submit(_worker_task, task)] = task
            if not inflight:
                break
            done, _ = cf.wait(list(inflight), timeout=1.0, return_when=cf.FIRST_COMPLETED)
            for fut in done:
                inflight.pop(fut)
                res = fut.result()
                session_keys += res["keys"]
                handle_hits(res)
                planner.complete(res["job"], res["idx"], res["keys"], res["finished"])
                if found and stop_on_found and not stopping:
                    stopping = True
                    stop_event.set()
            now = time.time()
            if stop_file and not stopping and os.path.exists(stop_file):
                log.info("Stop file %r found - finishing current chunks and saving.", stop_file)
                stopping = True
                stop_event.set()
            if now - t_status >= status_every:
                t_status = now
                rate = session_keys / max(now - t_start, 1e-9)
                parts = []
                for j in jobs[:3]:
                    full = j.size / rate if rate else float("inf")
                    parts.append(f"{j.label} {fmt_pct(100 * j.keys_done / j.size)} scanned, "
                                 f"full range at this speed: {fmt_duration(full)}")
                if len(jobs) > 3:
                    parts.append(f"+{len(jobs) - 3} more ranges")
                log.info("%s keys this session | %s keys/s | %s", fmt_num(session_keys), fmt_num(rate),
                         " | ".join(parts))
    except KeyboardInterrupt:
        log.info("Stop requested - stopping workers and saving progress (Ctrl+C again to force quit)...")
        stop_event.set()
        try:
            for fut in cf.as_completed(list(inflight)):
                inflight.pop(fut)
                try:
                    res = fut.result()
                except Exception:
                    continue
                session_keys += res["keys"]
                handle_hits(res)
                planner.complete(res["job"], res["idx"], res["keys"], res["finished"])
        except KeyboardInterrupt:
            pass
    finally:
        stop_event.set()
        if sys.version_info >= (3, 9):
            pool.shutdown(wait=True, cancel_futures=True)
        else:
            pool.shutdown(wait=True)
        db.close()

    elapsed = time.time() - t_start
    log.info("Session: %s keys in %s (%s keys/s). Unfinished chunks are redone next run.",
             fmt_num(session_keys), fmt_duration(elapsed), fmt_num(session_keys / max(elapsed, 1e-9)))
    if not found and not planner.active():
        log.info("Range fully scanned - no match.")
    return found


