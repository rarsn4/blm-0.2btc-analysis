###############################################################################
# secp256k1
###############################################################################
P = 0xFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFEFFFFFC2F
N = 0xFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFEBAAEDCE6AF48A03BBFD25E8CD0364141
GX = 0x79BE667EF9DCBBAC55A06295CE870B07029BFCDB2DCE28D959F2815B16F81798
GY = 0x483ADA7726A3C4655DA4FBFC0E1108A8FD17B448A68554199C47D08FFB10D4B8
G = (GX, GY)

Point = Optional[Tuple[int, int]]  # None is the point at infinity


def ec_add(p1: Point, p2: Point) -> Point:
    """Affine point addition (handles doubling and infinity). Setup use only."""
    if p1 is None:
        return p2
    if p2 is None:
        return p1
    x1, y1 = p1
    x2, y2 = p2
    if x1 == x2:
        if (y1 + y2) % P == 0:
            return None
        lam = 3 * x1 * x1 * pow(2 * y1, -1, P) % P
    else:
        lam = (y2 - y1) * pow(x2 - x1, -1, P) % P
    x3 = (lam * lam - x1 - x2) % P
    return x3, (lam * (x1 - x3) - y1) % P


def ec_mul(k: int, pt: Point = G) -> Point:
    """Scalar multiplication k*pt (double-and-add). ~2 ms; used once per chunk."""
    k %= N
    acc: Point = None
    while k:
        if k & 1:
            acc = ec_add(acc, pt)
        pt = ec_add(pt, pt)
        k >>= 1
    return acc


def pubkey_compressed(k: int) -> bytes:
    x, y = ec_mul(k)
    return (b"\x03" if y & 1 else b"\x02") + x.to_bytes(32, "big")


