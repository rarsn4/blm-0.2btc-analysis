def fmt_num(x: float) -> str:
    if abs(x) >= 1e15:
        return f"{x:.3g}"
    for unit, div in (("T", 1e12), ("G", 1e9), ("M", 1e6), ("k", 1e3)):
        if abs(x) >= div:
            return f"{x / div:.2f}{unit}"
    return f"{x:.0f}"


def fmt_duration(sec: float) -> str:
    if sec == float("inf") or sec != sec:
        return "forever"
    if sec < 120:
        return f"{sec:.0f} s"
    if sec < 7200:
        return f"{sec / 60:.0f} min"
    if sec < 172800:
        return f"{sec / 3600:.1f} h"
    days = sec / 86400
    if days < 730:
        return f"{days:.0f} days"
    years = days / 365.25
    for word, div in (("trillion", 1e12), ("billion", 1e9), ("million", 1e6), ("thousand", 1e3)):
        if years >= div:
            return f"{years / div:,.1f} {word} years"
    return f"{years:,.0f} years"


def fmt_pct(x: float) -> str:
    if x == 0:
        return "0%"
    if x < 1e-4:
        return f"{x:.2e}%"
    return f"{x:.4f}%"


