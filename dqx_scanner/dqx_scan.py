B58 = "123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz"


def b58encode(raw: bytes) -> str:
    n = int.from_bytes(raw, "big")
    out = []
    while n:
        n, r = divmod(n, 58)
        out.append(B58[r])
    pad = len(raw) - len(raw.lstrip(b"\x00"))
    return "1" * pad + "".join(reversed(out))


def b58decode(s: str) -> bytes:
    n = 0
    for ch in s:
        i = B58.find(ch)
        if i < 0:
            raise ValueError(f"invalid Base58 character {ch!r}")
        n = n * 58 + i
    pad = len(s) - len(s.lstrip("1"))
    body = n.to_bytes((n.bit_length() + 7) // 8, "big") if n else b""
    return b"\x00" * pad + body


def b58check_encode(payload: bytes) -> str:
    return b58encode(payload + _sha256(_sha256(payload).digest()).digest()[:4])


def b58check_decode(s: str) -> bytes:
    raw = b58decode(s)
    payload, chk = raw[:-4], raw[-4:]
    if len(raw) < 5 or _sha256(_sha256(payload).digest()).digest()[:4] != chk:
        raise ValueError(f"bad Base58Check checksum: {s}")
    return payload


def address_to_hash160(addr: str) -> bytes:
    payload = b58check_decode(addr.strip())
    if len(payload) != 21 or payload[0] != 0x00:
        raise ValueError(f"{addr} is not a mainnet P2PKH (1...) address")
    return payload[1:]


def hash160_to_address(h: bytes) -> str:
    return b58check_encode(b"\x00" + h)


def key_to_address(k: int) -> str:
    return hash160_to_address(hash160(pubkey_compressed(k)))


def key_to_wif(k: int) -> str:
    return b58check_encode(b"\x80" + k.to_bytes(32, "big") + b"\x01")  # compressed


