def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser(
        description="DQX Puzzle Scanner - exhaustive hash160 search over Bitcoin puzzle key ranges.",
        formatter_class=argparse.RawDescriptionHelpFormatter, epilog=__doc__.split("Commands", 1)[1])
    ap.add_argument("-v", "--verbose", action="store_true")
    ap.add_argument("--log-file", default="dqx_scan.log")
    sub = ap.add_subparsers(dest="cmd", required=True)
    cpu = os.cpu_count() or 1

    s = sub.add_parser("scan", help="search a puzzle or a custom range")
    s.add_argument("--puzzle", help="e.g. 71, 71-100, 71,72,73")
    s.add_argument("--address", action="append", help="custom P2PKH target (repeatable)")
    s.add_argument("--start", help="hex, dec:<n>, or percent of the puzzle range (inclusive)")
    s.add_argument("--end", help="hex, dec:<n>, or percent of the puzzle range (inclusive)")
    s.add_argument("--shard", help="i/n: scan only part i of n (split work across machines)")
    s.add_argument("--mode", choices=["auto", "random", "sequential"], default="auto",
                   help="auto = random for ranges > 2^48 keys, else sequential")
    s.add_argument("--workers", type=int, default=cpu, help=f"processes (default {cpu})")
    s.add_argument("--chunk-bits", type=int, default=21, help="chunk = 2^bits keys (default 21, ~8 s/core)")
    s.add_argument("--include-solved", action="store_true", help="allow known-solved puzzles")
    s.add_argument("--state", default="dqx_state.db", help="progress database")
    s.add_argument("--found", default="FOUND_KEYS.txt", help="where found keys are appended")
    s.add_argument("--status-every", type=float, default=15.0, help="seconds between status lines")
    s.add_argument("--stop-file", default="STOP", help="create this file to stop gracefully")
    s.set_defaults(func=cmd_scan)

    l_ = sub.add_parser("list", help="show puzzles, ranges and odds")
    l_.add_argument("--puzzle", help="subset, e.g. 71-80 (default 71-100)")
    l_.add_argument("--online", action="store_true", help="look up live balances on mempool.space")
    l_.add_argument("--rate", type=float, default=1e6, help="keys/s for the time estimates")
    l_.set_defaults(func=cmd_list)

    b = sub.add_parser("bench", help="measure keys/s on this machine")
    b.add_argument("--workers", type=int, default=cpu)
    b.add_argument("--seconds", type=float, default=10.0)
    b.set_defaults(func=cmd_bench)

    t = sub.add_parser("selftest", help="verify correctness on known data")
    t.add_argument("--workers", type=int, default=min(cpu, 4))
    t.set_defaults(func=cmd_selftest)

    args = ap.parse_args(argv)
    handlers: List[logging.Handler] = [logging.StreamHandler(sys.stdout)]
    if args.cmd == "scan" and args.log_file:
        handlers.append(logging.FileHandler(args.log_file, encoding="utf-8"))
    logging.basicConfig(level=logging.DEBUG if args.verbose else logging.INFO,
                        format="%(asctime)s %(levelname)s %(message)s", handlers=handlers)
    if args.cmd in ("scan", "bench", "selftest") and getattr(args, "workers", 1) < 1:
        raise SystemExit("--workers must be >= 1")
    if args.cmd == "scan" and not 12 <= args.chunk_bits <= 40:
        raise SystemExit("--chunk-bits must be between 12 and 40")
    return args.func(args)


