@dataclass
class Job:
    label: str
    addresses: List[str]
    start: int
    end: int
    chunk_size: int
    puzzle: Optional[int] = None
    frontier: int = 0          # sequential: every chunk below this is done
    keys_done: int = 0
    chunks_done: int = 0
    next_idx: int = 0
    done_set: Set[int] = field(default_factory=set)
    inflight: Set[int] = field(default_factory=set)
    exhausted: bool = False

    @property
    def size(self) -> int:
        return self.end - self.start + 1

    @property
    def nchunks(self) -> int:
        return (self.size + self.chunk_size - 1) // self.chunk_size

    @property
    def key(self) -> str:
        return f"{self.label}|{self.start:x}|{self.end:x}|cs{self.chunk_size}"

    def chunk_bounds(self, idx: int) -> Tuple[int, int]:
        a = self.start + idx * self.chunk_size
        return a, min(self.end, a + self.chunk_size - 1)


class Planner:
    """Hands out chunks: sequential (round-robin across jobs) or random."""

    def __init__(self, jobs: List[Job], mode: str, db: StateDB):
        self.jobs = jobs
        self.mode = mode
        self.db = db
        self.rr = 0
        for j in jobs:
            db.load_job(j)
            j.next_idx = j.frontier
            if mode == "sequential":
                j.done_set = db.done_above(j, j.frontier)
            if j.chunks_done >= j.nchunks:
                j.exhausted = True

    def active(self) -> List[Job]:
        return [j for j in self.jobs if not j.exhausted]

    def next_task(self) -> Optional[Tuple[int, int, int, int]]:
        if self.mode == "sequential":
            return self._next_sequential()
        return self._next_random()

    def _next_sequential(self):
        for _ in range(len(self.jobs)):
            ji = self.rr % len(self.jobs)
            self.rr += 1
            j = self.jobs[ji]
            if j.exhausted:
                continue
            while j.next_idx < j.nchunks and j.next_idx in j.done_set:
                j.next_idx += 1
            if j.next_idx >= j.nchunks:
                continue  # everything dispatched; exhausted once in-flight work lands
            idx = j.next_idx
            j.next_idx += 1
            j.inflight.add(idx)
            return (ji, idx) + j.chunk_bounds(idx)
        return None

    def _next_random(self):
        jobs = [(i, j) for i, j in enumerate(self.jobs)
                if not j.exhausted and j.chunks_done + len(j.inflight) < j.nchunks]
        if not jobs:
            return None
        ji, j = jobs[secrets.randbelow(len(jobs))]
        for _ in range(64):
            idx = secrets.randbelow(j.nchunks)
            if idx not in j.inflight and not self.db.is_done(j, idx):
                break
        else:  # small, nearly finished range: take the first free chunk
            idx = next((x for x in range(j.nchunks)
                        if x not in j.inflight and not self.db.is_done(j, x)), None)
            if idx is None:
                return None
        j.inflight.add(idx)
        return (ji, idx) + j.chunk_bounds(idx)

    def complete(self, ji: int, idx: int, keys: int, finished: bool) -> None:
        j = self.jobs[ji]
        j.inflight.discard(idx)
        if not finished:
            if self.mode == "sequential":
                j.next_idx = min(j.next_idx, idx)  # redo it next time
            return
        j.keys_done += keys
        j.chunks_done += 1
        if self.mode == "sequential":
            j.done_set.add(idx)
            while j.frontier in j.done_set:
                j.done_set.discard(j.frontier)
                j.frontier += 1
        self.db.mark_done(j, idx, keys)
        if j.chunks_done >= j.nchunks:
            j.exhausted = True


