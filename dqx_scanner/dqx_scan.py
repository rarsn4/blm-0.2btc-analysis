class StateDB:
    def __init__(self, path: str):
        self.path = path
        self.conn = sqlite3.connect(path, timeout=30)
        self.conn.execute("PRAGMA journal_mode=WAL")
        self.conn.executescript("""
            CREATE TABLE IF NOT EXISTS jobs(
                job_key TEXT PRIMARY KEY, label TEXT, start_hex TEXT, end_hex TEXT,
                chunk_size INTEGER, frontier_hex TEXT DEFAULT '0',
                keys_done INTEGER DEFAULT 0, chunks_done INTEGER DEFAULT 0, updated TEXT);
            CREATE TABLE IF NOT EXISTS chunks(
                job_key TEXT, idx TEXT, PRIMARY KEY(job_key, idx)) WITHOUT ROWID;
            CREATE TABLE IF NOT EXISTS found(
                ts TEXT, label TEXT, address TEXT, key_hex TEXT, wif TEXT);
        """)
        self.conn.commit()

    @staticmethod
    def _ix(idx: int) -> str:
        return format(idx, "032x")  # fixed width, so text order == numeric order

    def load_job(self, job) -> None:
        row = self.conn.execute(
            "SELECT frontier_hex, keys_done, chunks_done FROM jobs WHERE job_key=?", (job.key,)).fetchone()
        if row is None:
            self.conn.execute(
                "INSERT INTO jobs(job_key,label,start_hex,end_hex,chunk_size,updated) VALUES(?,?,?,?,?,datetime('now'))",
                (job.key, job.label, hex(job.start), hex(job.end), job.chunk_size))
            self.conn.commit()
            return
        job.frontier = int(row[0], 16)
        job.keys_done = int(row[1])
        job.chunks_done = int(row[2])

    def done_above(self, job, frontier: int, limit: int = 5_000_000) -> Set[int]:
        rows = self.conn.execute(
            "SELECT idx FROM chunks WHERE job_key=? AND idx>=? LIMIT ?", (job.key, self._ix(frontier), limit))
        return {int(r[0], 16) for r in rows}

    def is_done(self, job, idx: int) -> bool:
        return self.conn.execute(
            "SELECT 1 FROM chunks WHERE job_key=? AND idx=?", (job.key, self._ix(idx))).fetchone() is not None

    def mark_done(self, job, idx: int, keys: int) -> None:
        self.conn.execute("INSERT OR IGNORE INTO chunks(job_key, idx) VALUES(?,?)", (job.key, self._ix(idx)))
        self.conn.execute(
            "UPDATE jobs SET frontier_hex=?, keys_done=?, chunks_done=?, updated=datetime('now') WHERE job_key=?",
            (hex(job.frontier), job.keys_done, job.chunks_done, job.key))
        self.conn.commit()

    def record_found(self, label: str, address: str, key: int) -> None:
        self.conn.execute("INSERT INTO found VALUES(datetime('now'),?,?,?,?)",
                          (label, address, format(key, "064x"), key_to_wif(key)))
        self.conn.commit()

    def close(self) -> None:
        self.conn.close()


